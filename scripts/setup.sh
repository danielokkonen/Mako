#!/usr/bin/env bash
# Interactive setup (Linux): collects job configs from ~/.local/share/Mako, generates a compose
# file (Postgres + one service per config) next to them, and starts the stack.
# Job configs are passed as raw YAML via --yaml (no runtime bind mounts of $CONFIG_DIR),
# so re-run this script after editing a config.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_DIR="${MAKO_CONFIG_DIR:-$HOME/.local/share/Mako}"
GENERATED="$CONFIG_DIR/mako.compose.yaml"
BUILD_DIR="$CONFIG_DIR/mako-build"
IMAGE="mako-host"

mkdir -p "$CONFIG_DIR"

if command -v podman >/dev/null 2>&1; then TOOL=podman
elif command -v docker >/dev/null 2>&1; then TOOL=docker
else echo "error: neither podman nor docker found on PATH" >&2; exit 1
fi

shopt -s nullglob
files=()
for f in "$CONFIG_DIR"/*.yaml "$CONFIG_DIR"/*.yml; do
  [[ "$(basename "$f")" == "mako.compose.yaml" ]] && continue
  files+=("$f")
done
if (( ${#files[@]} == 0 )); then
  echo "No job configs found in $CONFIG_DIR."
  echo "Copy one of the job configs from $ROOT/examples (anything but compose.yaml) and re-run this script."
  exit 1
fi

read -r -p "Host port for Postgres [5432]: " PORT
PORT="${PORT:-5432}"

# Stage a build context: app sources plus the repo's Dockerfile. No configs are baked into the
# image and no bind mount of $CONFIG_DIR is needed — each service passes its config as raw YAML
# via --yaml, so containers never need host access at runtime (rootless runtimes under SELinux
# deny such mounts anyway).
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"
cp -r "$ROOT/src" "$BUILD_DIR/"
cp "$ROOT/examples/Dockerfile" "$BUILD_DIR/Dockerfile"

{
  echo "# Generated by scripts/setup.sh — re-run the script to regenerate. Do not edit by hand."
  echo "# Job configs are passed as raw YAML via --yaml; edit a config and re-run this script to apply it."
  echo "name: mako"
  echo ""
  echo "services:"
  echo "  db:"
  echo "    image: postgres:18"
  echo "    environment:"
  echo "      POSTGRES_USER: user"
  echo "      POSTGRES_PASSWORD: password"
  echo "      POSTGRES_DB: mako"
  echo "    ports:"
  echo "      - \"$PORT:5432\""
  echo "    volumes:"
  echo "      - mako-db:/var/lib/postgresql"
  echo "    healthcheck:"
  echo '      test: ["CMD-SHELL", "pg_isready -U user -d mako"]'
  echo "      interval: 5s"
  echo "      timeout: 3s"
  echo "      retries: 10"
  for f in "${files[@]}"; do
    base="$(basename "$f")"
    stem="${base%.*}"
    name="$(printf '%s' "$stem" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9._-' '-')"
    read -r -p "Cron schedule for $base (empty = run once and stop): " SCHED
    RESTART='"no"'
    echo ""
    echo "  $name:"
    echo "    build:"
    echo "      context: \"$BUILD_DIR\""
    echo "      dockerfile: Dockerfile"
    echo "    image: $IMAGE"
    # The config is inlined as a block scalar so it reaches the container as one raw-YAML argv element.
    echo "    command:"
    echo "      - --yaml"
    echo "      - |"
    while IFS= read -r line || [[ -n "$line" ]]; do
      printf '        %s\n' "$line"
    done < "$f"
    if [[ -n "$SCHED" ]]; then
      echo "      - \"--schedule\""
      echo "      - \"$SCHED\""
      RESTART="unless-stopped"
    fi
    echo "    environment:"
    echo '      TZ: ${MAKO_TZ:-UTC}'
    echo "      MAKO_CONNECTION_STRING: Host=db;Port=5432;Username=user;Password=password;Database=mako"
    echo "    depends_on:"
    echo "      db:"
    echo "        condition: service_healthy"
    echo "    restart: $RESTART"
  done
  echo ""
  echo "volumes:"
  echo "  mako-db:"
} > "$GENERATED"

echo "Wrote $GENERATED — starting the stack with $TOOL…"
$TOOL compose -f "$GENERATED" up -d --build
echo
echo "Stack is up. Manage it with: $TOOL compose -f \"$GENERATED\" <logs|down>"

rm -rf "$BUILD_DIR"
